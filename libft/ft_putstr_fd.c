#include "libft.h"

void	ft_putstr_fd(char *s, int fd)
{
	int		i;
	char	*str;

	i = 0;
	str = (char *)s;
	while (str[i] != '\0')
	{
		write(fd, &str[i], 1);
		i++;
	}
}
